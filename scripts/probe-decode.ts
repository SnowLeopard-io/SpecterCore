import { X86Decoder } from '@specter-core/core';
const bytes = new Uint8Array([0x8b,0xff,0x53,0x56,0x57,0x8b,0xf9,0x8b,0xf7,0x8d,0x4e,0x02,0x0f,0x1f,0x40,0x00,0x66,0x8b,0x06,0x83,0xc6,0x02,0x66,0x85,0xc0,0x75,0xf5,0x2b,0xf1,0xd1,0xfe,0x46]);
const dec = new X86Decoder('x86');
try {
  const r = dec.decode(bytes, 0x40eb20);
  console.log('terminated=', r.terminated, 'end=', '0x'+(r.endAddress>>>0).toString(16));
  for (const d of r.instructions) console.log('0x'+(d.address>>>0).toString(16), d.inst.op, JSON.stringify(d.inst.dst), JSON.stringify(d.inst.src));
} catch (e) {
  console.log('DECODE ERROR:', (e as Error).message);
}
